namespace Domain.Enums;

/// <summary>
/// Represents the intended use or purpose of a real estate property.
/// </summary>
public enum Purpose
{
    /// <summary>
    /// Residential use (e.g., living space).
    /// </summary>
    Residential,

    /// <summary>
    /// Commercial use (e.g., business, retail).
    /// </summary>
    Commercial,

    /// <summary>
    /// Industrial use (e.g., factory, plant).
    /// </summary>
    Industrial,

    /// <summary>
    /// Agricultural use (e.g., farming, cultivation).
    /// </summary>
    Agricultural,

    /// <summary>
    /// Mixed-use (combination of residential, commercial, etc.).
    /// </summary>
    MixedUse
}