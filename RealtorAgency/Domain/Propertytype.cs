namespace Domain;

/// <summary>
/// Represents the type of a real estate property.
/// </summary>
public enum PropertyType
{
    /// <summary>
    /// An apartment.
    /// </summary>
    Apartment,

    /// <summary>
    /// A private house.
    /// </summary>
    House,

    /// <summary>
    /// An office space.
    /// </summary>
    Office,

    /// <summary>
    /// A warehouse.
    /// </summary>
    Warehouse,

    /// <summary>
    /// A land plot.
    /// </summary>
    LandPlot,

    /// <summary>
    /// A commercial space (e.g., retail unit).
    /// </summary>
    CommercialSpace
}